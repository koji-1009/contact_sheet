// Generates lib/src/html_js.g.dart from lib/src/html/app.js and
// lib/src/html/app.css: index.html's own script and style, which the export
// inlines (the command carries them in the binary, where lib/src/html/ is
// not read). Run from the repository's root after changing either:
//
//   dart run tool/gen_html.dart
import 'dart:io';

const _files = [
  (
    file: 'lib/src/html/app.js',
    name: 'appJs',
    doc: 'index.html\'s script, `lib/src/html/app.js`.',
  ),
  (
    file: 'lib/src/html/app.css',
    name: 'appCss',
    doc: 'index.html\'s style past the map\'s palette, `lib/src/html/app.css`.',
  ),
];

Future<void> main() async {
  final b = StringBuffer()
    ..writeln('// Generated by tool/gen_html.dart from lib/src/html/app.js and')
    ..writeln('// lib/src/html/app.css: do not edit.');
  for (final (:file, :name, :doc) in _files) {
    final text = File(file).readAsStringSync();
    // A raw string holds the text as it is, but for its own delimiter; and
    // inlined, nothing in it may end its element.
    for (final bad in ["'''", '</script', '</style']) {
      if (text.toLowerCase().contains(bad)) {
        stderr.writeln('$file holds $bad.');
        exitCode = 1;
        return;
      }
    }
    b
      ..writeln()
      ..writeln('/// $doc')
      ..writeln("const $name = r'''")
      ..write(text)
      ..writeln("''';");
  }
  const generated = 'lib/src/html_js.g.dart';
  File(generated).writeAsStringSync('$b');
  // As `dart format` has it, so that formatting changes nothing.
  final formatted = await Process.run(Platform.resolvedExecutable, [
    'format',
    generated,
  ]);
  if (formatted.exitCode != 0) {
    stderr.write(formatted.stderr);
    exitCode = formatted.exitCode;
  }
}
