// Compiles the route's search (tool/route_js.dart, lib/src/route.dart) to
// JavaScript and writes it into lib/src/route_js.g.dart, which index.html
// inlines, formatted. Run from the repository's root after changing either:
//
//   dart run tool/gen_route_js.dart
import 'dart:convert';
import 'dart:io';

import 'route_sources.dart';

Future<void> main() async {
  final temp = Directory.systemTemp.createTempSync('contact_sheet_route');
  try {
    final out = '${temp.path}/route.js';
    final compiled = await Process.run(Platform.resolvedExecutable, [
      'compile',
      'js',
      '-O2',
      '--no-source-maps',
      '-o',
      out,
      'tool/route_js.dart',
    ]);
    if (compiled.exitCode != 0) {
      stderr
        ..write(compiled.stdout)
        ..write(compiled.stderr);
      exitCode = compiled.exitCode;
      return;
    }
    final js = File(out).readAsStringSync().trim();
    // As a Dart string: JSON's escapes are Dart's, but for `$`.
    final literal = jsonEncode(js).replaceAll(r'$', r'\$');
    const generated = 'lib/src/route_js.g.dart';
    File(generated).writeAsStringSync(
      '// Generated by tool/gen_route_js.dart from '
      '${routeSources.join(' and ')}: do not edit.\n'
      '// sources: ${routeSourcesHash()}\n'
      '\n'
      '/// The route\'s search, compiled to JavaScript: `index.html` inlines\n'
      '/// it, and calls `contactSheetRouter(sheetJson)(from, state, to)`.\n'
      'const routeJs = $literal;\n',
    );
    // As `dart format` has it, so that formatting changes nothing.
    final formatted = await Process.run(Platform.resolvedExecutable, [
      'format',
      generated,
    ]);
    if (formatted.exitCode != 0) {
      stderr.write(formatted.stderr);
      exitCode = formatted.exitCode;
    }
  } finally {
    temp.deleteSync(recursive: true);
  }
}
