// Generates lib/src/docs.dart from doc/agent.md and doc/manual.md: the
// documents the command prints, carried in the binary, where `doc/` is not.
// Run from the repository's root after changing either:
//
//   dart run tool/gen_docs.dart
import 'dart:io';

const _docs = [
  (
    file: 'doc/agent.md',
    name: 'agentText',
    doc: '`sheet agent`: the step-by-step playbook, `doc/agent.md`.',
  ),
  (
    file: 'doc/manual.md',
    name: 'manualText',
    doc: '`sheet manual`: the reference, `doc/manual.md`.',
  ),
];

Future<void> main() async {
  final b = StringBuffer()
    ..writeln('// Generated by tool/gen_docs.dart from doc/agent.md and')
    ..writeln('// doc/manual.md: do not edit. The documents for AI agents that')
    ..writeln(
      '// the command prints, in English whatever the user\'s language.',
    );
  for (final (:file, :name, :doc) in _docs) {
    final text = File(file).readAsStringSync();
    // A raw string holds the text as it is, but for its own delimiter.
    if (text.contains("'''")) {
      stderr.writeln("$file holds ''': it cannot be a raw string.");
      exitCode = 1;
      return;
    }
    b
      ..writeln()
      ..writeln('/// $doc')
      ..writeln("const $name = r'''")
      ..write(text)
      ..writeln("''';");
  }
  const generated = 'lib/src/docs.dart';
  File(generated).writeAsStringSync('$b');
  // As `dart format` has it, so that formatting changes nothing.
  final formatted = await Process.run(Platform.resolvedExecutable, [
    'format',
    generated,
  ]);
  if (formatted.exitCode != 0) {
    stderr.write(formatted.stderr);
    exitCode = formatted.exitCode;
  }
}
