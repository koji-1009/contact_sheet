// Generates lib/src/messages.g.dart from lib/src/l10n/messages_*.arb:
//
//   dart run tool/gen_messages.dart
//
// The command line is pure Dart and has no BuildContext, so Flutter's
// gen-l10n, which makes Flutter localizations, does not apply. The ARB
// files are read the same way: the English one is the
// template, its `@key.placeholders` give each message's parameters, and
// `{name}` in a message is replaced by the parameter. The file is written
// formatted.
import 'dart:convert';
import 'dart:io';

Future<void> main() async {
  final dir = Directory.fromUri(Platform.script.resolve('../lib/src/l10n/'));
  final arbs = {
    for (final file in dir.listSync().whereType<File>())
      if (RegExp(r'messages_(\w+)\.arb$').firstMatch(file.path) case final m?)
        m[1]!: jsonDecode(file.readAsStringSync()) as Map<String, Object?>,
  };
  final template = arbs['en']!;
  final keys = [
    for (final key in template.keys)
      if (!key.startsWith('@')) key,
  ];
  List<String> params(String key) {
    final meta = template['@$key'];
    final placeholders = meta is Map ? meta['placeholders'] : null;
    return placeholders is Map ? [...placeholders.keys.cast<String>()] : [];
  }

  for (final MapEntry(key: locale, value: arb) in arbs.entries) {
    final missing = keys.where((k) => !arb.containsKey(k));
    if (missing.isNotEmpty) {
      stderr.writeln('messages_$locale.arb lacks: ${missing.join(', ')}');
      exitCode = 1;
      return;
    }
  }

  final locales = arbs.keys.toList()..sort();
  String className(String locale) =>
      'Messages${locale[0].toUpperCase()}${locale.substring(1)}';
  String literal(String text, List<String> names) {
    var out = jsonEncode(text).replaceAll(r'$', r'\$');
    for (final name in names) {
      out = out.replaceAll('{$name}', '\${$name}');
    }
    return out;
  }

  final b = StringBuffer()
    ..writeln('// Generated by tool/gen_messages.dart from lib/src/l10n/*.arb.')
    ..writeln('// Do not edit: change the ARB files and run it again.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln('/// The command line\'s words.')
    ..writeln('abstract class Messages {')
    ..writeln('  const Messages();')
    ..writeln()
    ..writeln('  /// The words for [locale] (`ja`, `ja_JP`, `en-US`, ...), or')
    ..writeln('  /// English when there are none for its language.')
    ..writeln('  static Messages of(String locale) =>')
    ..writeln("      switch (locale.split(RegExp('[-_.]')).first) {");
  for (final locale in locales) {
    b.writeln("        '$locale' => const ${className(locale)}(),");
  }
  b
    ..writeln('        _ => const MessagesEn(),')
    ..writeln('      };')
    ..writeln()
    ..writeln('  /// The language of these words: `en`, `ja`.')
    ..writeln('  String get localeName;')
    ..writeln();
  for (final key in keys) {
    final names = params(key);
    b.writeln(
      names.isEmpty
          ? '  String get $key;'
          : '  String $key(${names.map((n) => 'Object $n').join(', ')});',
    );
  }
  b.writeln('}');
  for (final locale in locales) {
    final arb = arbs[locale]!;
    b
      ..writeln()
      ..writeln('class ${className(locale)} extends Messages {')
      ..writeln('  const ${className(locale)}();')
      ..writeln()
      ..writeln('  @override')
      ..writeln("  String get localeName => '$locale';");
    for (final key in keys) {
      final names = params(key);
      final text = literal(arb[key]! as String, names);
      b
        ..writeln()
        ..writeln('  @override')
        ..writeln(
          names.isEmpty
              ? '  String get $key => $text;'
              : '  String $key(${names.map((n) => 'Object $n').join(', ')}) =>\n      $text;',
        );
    }
    b.writeln('}');
  }
  final generated = Platform.script.resolve('../lib/src/messages.g.dart');
  File.fromUri(generated).writeAsStringSync('$b');
  // As `dart format` has it, so that formatting changes nothing.
  final formatted = await Process.run(Platform.resolvedExecutable, [
    'format',
    generated.toFilePath(),
  ]);
  if (formatted.exitCode != 0) {
    stderr.write(formatted.stderr);
    exitCode = formatted.exitCode;
  }
}
